// Synchronize the hub repository with GitHub: status, incoming changes to pull, local changes to push.
// Uses git exclusively, with args controlled by code (no arbitrary text, no shell). Never uses force push:
// if branches have diverged, it halts and reports it. Zero dependencies.
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { platformLabel } from './machine.mjs';
import { hashPath, readJson, toPosix } from './util.mjs';
import { tFor } from './i18n.mjs';

const t = tFor();

const MAX_OUTPUT = 1024 * 1024;
const MAX_LISTED = 40;
// Versioned files generated by the hub: contain no user choices, safe to reset and regenerate
export const GENERATED_FILES = ['GUIDE.md'];
const NAME_RE = /^[\w.-]+$/; // name of a "remote" (origin)
const UPSTREAM_RE = /^[\w.-]+\/[\w./-]+$/; // origin/main
const BRANCH_RE = /^[\w./-]+$/;
const SHA_RE = /^[0-9a-f]{7,64}$/;

// Files that are never sent automatically: look like keys or secrets.
const SECRET_RE = /(^|\/)(\.env(\.[\w.-]+)?|id_(rsa|dsa|ecdsa|ed25519)(\.pub)?|[^/]*\.(pem|key|p12|pfx)|credentials?\.json|\.npmrc|\.netrc|[^/]*secret[^/]*)$/i;
const SECRET_OK_RE = /\.(example|sample|template|pub)$/i;
export const looksSecret = (p) => SECRET_RE.test(p) && !SECRET_OK_RE.test(p);

// Real secrets recognizable from content, regardless of file name.
const contentSecrets = () => [
  [/-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP |ENCRYPTED )?PRIVATE KEY(?: BLOCK)?-----/, t('repo.secret.privateKey')],
  [/\bAKIA[0-9A-Z]{16}\b/, t('repo.secret.awsKey')],
  [/\bgh[pousr]_[A-Za-z0-9]{36,}\b|\bgithub_pat_[A-Za-z0-9_]{60,}/, t('repo.secret.githubToken')],
  [/\bsk-ant-[A-Za-z0-9_-]{40,}/, t('repo.secret.anthropicKey')],
  [/\bsk-(?:proj-)?[A-Za-z0-9]{20}T3BlbkFJ[A-Za-z0-9]{20}|\bsk-proj-[A-Za-z0-9_-]{60,}/, t('repo.secret.openaiKey')],
  [/\bxox[abprs]-[0-9]{6,}-[A-Za-z0-9-]{10,}/, t('repo.secret.slackToken')],
  [/\bAIza[0-9A-Za-z_-]{35}\b/, t('repo.secret.googleKey')],
];
const SCAN_FILE_MAX = 1024 * 1024; // files larger than 1 MB: only read the first MB
const SCAN_TOTAL_MAX = 64 * 1024 * 1024;

/** Why a text appears to contain a secret, or null. */
export function secretInText(text) {
  for (const [re, why] of contentSecrets()) if (re.test(text)) return why;
  return null;
}

/**
 * External copies from GitHub installed by the hub and unmodified (same hash recorded in lock):
 * their NAME alone is not enough to block them (e.g. "secret-scanner.py" in a public skill). Content is still checked.
 */
function untouchedExternal(root) {
  let entries = [];
  try {
    entries = readJson(path.join(root, 'manifest.lock.json'), { entries: [] }).entries ?? [];
  } catch {
    return () => false;
  }
  const ok = new Map(); // element path → unmodified?
  const owner = (p) => entries.find((e) => typeof e.path === 'string' && /^(skills|agents)\/external\//.test(e.path) && (p === e.path || p.startsWith(`${e.path}/`)));
  return (p) => {
    const e = owner(p);
    if (!e || !e.contentHash) return false;
    if (!ok.has(e.path)) {
      let same = false;
      try {
        same = hashPath(path.join(root, e.path)) === e.contentHash;
      } catch {
        /* missing or unreadable: do not exempt */
      }
      ok.set(e.path, same);
    }
    return ok.get(e.path);
  };
}

/**
 * Modified files that must not be pushed, with reasons: [{path, reason}].
 * - content with recognizable secret → always blocked;
 * - secret filename (.env, *.key, *secret*…) → blocked, except unmodified copies from GitHub.
 */
export function findSecrets(root, paths) {
  const external = untouchedExternal(root);
  const out = [];
  let budget = SCAN_TOTAL_MAX;
  for (const p of paths) {
    let reason = null;
    const abs = path.join(root, p);
    if (budget > 0) {
      try {
        const st = fs.lstatSync(abs);
        if (st.isFile()) {
          const len = Math.min(st.size, SCAN_FILE_MAX);
          const buf = Buffer.alloc(len);
          const fd = fs.openSync(abs, 'r');
          try {
            fs.readSync(fd, buf, 0, len, 0);
          } finally {
            fs.closeSync(fd);
          }
          budget -= len;
          reason = secretInText(buf.toString('latin1'));
        }
      } catch {
        /* deleted or unreadable: file name check still applies */
      }
    }
    if (!reason && looksSecret(p) && !external(toPosix(p))) reason = t('repo.secret.fileName');
    if (reason) out.push({ path: p, reason });
  }
  return out;
}

/** Strips username and password from a URL (https://user:token@github.com/...) before displaying or saving it. */
export const cleanUrl = (s) => String(s ?? '').replace(/(\b[a-z][a-z0-9+.-]*:\/\/)[^/@\s]+@/gi, '$1');

function killTree(child) {
  try {
    if (process.platform === 'win32') spawnSync('taskkill', ['/pid', String(child.pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true });
    else process.kill(-child.pid, 'SIGKILL');
  } catch {
    try {
      child.kill('SIGKILL');
    } catch {
      /* already terminated */
    }
  }
}

/** Runs git with fixed arguments, no shell. Never prompts for password in terminal; returns safely. */
export function git(root, args, { timeout = 30000, interactive = false } = {}) {
  return new Promise((resolve) => {
    const env = { ...process.env, GIT_TERMINAL_PROMPT: '0', GIT_OPTIONAL_LOCKS: '0', LC_ALL: 'C', LANGUAGE: 'C' };
    // In background checks, credential manager must not open login dialogs.
    if (!interactive) env.GCM_INTERACTIVE = 'never';
    let out = '';
    let err = '';
    let timedOut = false;
    let notFound = false;
    let settled = false;
    const cap = (s) => (s.length > MAX_OUTPUT ? s.slice(0, MAX_OUTPUT) : s);
    const finish = (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve({ ok: code === 0 && !notFound && !timedOut, code, stdout: out.replace(/\s+$/, ''), stderr: err.replace(/\s+$/, ''), timedOut, notFound });
    };
    let child;
    try {
      // outside Windows git runs in its own process group: kills children on timeout
      child = spawn('git', ['-C', root, '-c', 'core.quotepath=false', ...args], { env, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true, detached: process.platform !== 'win32' });
    } catch (e) {
      notFound = e.code === 'ENOENT';
      err = e.message;
      return finish(null);
    }
    // On timeout kills git WITH its spawned children (hooks, credential helpers) and responds immediately
    const timer = setTimeout(() => {
      timedOut = true;
      killTree(child);
      finish(null);
    }, timeout);
    child.stdout.on('data', (d) => (out = cap(out + d)));
    child.stderr.on('data', (d) => (err = cap(err + d)));
    child.on('error', (e) => {
      notFound = e.code === 'ENOENT';
      err += e.message;
      finish(null);
    });
    child.on('close', (code) => finish(code));
  });
}

const errorText = () => ({
  offline: t('repo.error.offline'),
  auth: t('repo.error.auth'),
  rejected: t('repo.error.rejected'),
  'local-changes': t('repo.error.localChanges'),
  identity: t('repo.error.identity'),
  timeout: t('repo.error.timeout'),
  'no-git': t('repo.error.noGit'),
  other: t('repo.error.other'),
});

export function classifyError(r) {
  const t = `${r.stderr}\n${r.stdout}`.toLowerCase();
  if (r.notFound) return 'no-git';
  if (r.timedOut) return 'timeout';
  if (/authentication failed|could not read (username|password)|terminal prompts disabled|invalid credentials|permission denied|returned error: (401|403)|repository not found|\b(401|403)\b/.test(t)) return 'auth';
  if (/non-fast-forward|\[rejected\]|fetch first|updates were rejected/.test(t)) return 'rejected';
  if (/would be overwritten|your local changes|please commit your changes or stash/.test(t)) return 'local-changes';
  if (/please tell me who you are|unable to auto-detect email|empty ident name/.test(t)) return 'identity';
  if (/could not resolve host|unable to access|network is unreachable|timed out|failed to connect|could not connect|connection refused|early eof|ssl/.test(t)) return 'offline';
  return 'other';
}

/** { kind, message, detail } with git output cleaned of any credentials. */
export function describeError(r) {
  const kind = classifyError(r);
  const detail = cleanUrl(`${r.stderr}\n${r.stdout}`.trim()).split('\n').slice(-6).join('\n').slice(0, 600);
  return { kind, message: errorText()[kind], detail: kind === 'other' || kind === 'rejected' ? detail : '' };
}

function parsePorcelain(out) {
  const parts = out.split('\0');
  const files = [];
  for (let i = 0; i < parts.length; i++) {
    const e = parts[i];
    if (e.length < 4) continue;
    const xy = e.slice(0, 2);
    if (/[RC]/.test(xy)) i++; // after a rename the old name follows
    files.push({ path: e.slice(3), code: xy });
  }
  return files;
}

const fileLabel = (xy) => {
  if (/U|^AA$|^DD$/.test(xy)) return t('repo.fileLabel.conflict');
  if (xy === '??') return t('repo.fileLabel.new');
  if (/D/.test(xy)) return t('repo.fileLabel.deleted');
  if (/R/.test(xy)) return t('repo.fileLabel.renamed');
  if (/A/.test(xy)) return t('repo.fileLabel.added');
  return t('repo.fileLabel.modified');
};

function samePath(a, b) {
  const norm = (p) => {
    let r;
    try {
      r = fs.realpathSync.native(p);
    } catch {
      r = path.resolve(p);
    }
    return process.platform === 'win32' || process.platform === 'darwin' ? r.toLowerCase() : r;
  };
  return norm(a) === norm(b);
}

const parseLog = (out) =>
  out
    ? out.split('\n').map((l) => {
        const [hash, author, date, ...subject] = l.split('\t');
        return { hash, author, date, subject: subject.join('\t') };
      })
    : [];

/**
 * Repo snapshot. With { fetch: true } checks GitHub first (without modifying any of your files).
 * state: no-git | no-repo | detached | in-progress | no-remote | no-upstream | synced | behind | ahead | diverged
 */
async function computeStatus(root, { fetch = false, interactive = false } = {}) {
  const base = { state: 'no-repo', platform: platformLabel(), fetched: false, fetchError: null, lastFetch: null, branch: null, upstream: null, remote: null, remoteUrl: null, head: null, ahead: 0, behind: 0, incoming: [], outgoing: [], incomingFiles: [], needsSetup: false, changes: [], changesTotal: 0, blocked: [], blockedReasons: {}, blockedTotal: 0 };

  const top = await git(root, ['rev-parse', '--show-toplevel']);
  if (top.notFound) return { ...base, state: 'no-git' };
  // hub must be repo root: if inside another repo, do not touch that
  if (!top.ok || !samePath(top.stdout, root)) return { ...base, state: 'no-repo' };

  const [branchR, headR, gitDirR] = await Promise.all([git(root, ['symbolic-ref', '--short', '-q', 'HEAD']), git(root, ['rev-parse', 'HEAD']), git(root, ['rev-parse', '--git-dir'])]);
  const st = { ...base, branch: branchR.ok ? branchR.stdout : null, head: headR.ok ? headR.stdout : null };
  const gitDir = gitDirR.ok ? path.resolve(root, gitDirR.stdout) : null;

  // uncommitted changes
  const dirty = await git(root, ['status', '--porcelain=v1', '-z', '--untracked-files=all']);
  if (dirty.ok) {
    const all = parsePorcelain(dirty.stdout);
    st.changesTotal = all.length;
    st.changes = all.slice(0, MAX_LISTED).map((f) => ({ path: f.path, status: fileLabel(f.code) }));
    const secrets = findSecrets(root, all.map((f) => f.path));
    st.blockedTotal = secrets.length;
    st.blocked = secrets.slice(0, MAX_LISTED).map((x) => x.path);
    st.blockedReasons = Object.fromEntries(secrets.slice(0, MAX_LISTED).map((x) => [x.path, x.reason]));
    st.conflicts = all.some((f) => /U|^AA$|^DD$/.test(f.code));
  }

  if (gitDir && ['MERGE_HEAD', 'rebase-merge', 'rebase-apply', 'CHERRY_PICK_HEAD', 'REVERT_HEAD'].some((n) => fs.existsSync(path.join(gitDir, n)))) return { ...st, state: 'in-progress' };
  if (!st.branch) return { ...st, state: 'detached' };

  const up = await git(root, ['rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{u}']);
  if (!up.ok) {
    const remotes = await git(root, ['remote']);
    return { ...st, state: remotes.ok && remotes.stdout ? 'no-upstream' : 'no-remote' };
  }
  if (!UPSTREAM_RE.test(up.stdout)) return { ...st, state: 'no-upstream' };
  st.upstream = up.stdout;
  st.remote = up.stdout.split('/')[0];
  const url = NAME_RE.test(st.remote) ? await git(root, ['remote', 'get-url', st.remote]) : null;
  st.remoteUrl = url?.ok ? cleanUrl(url.stdout).replace(/\.git$/, '') : null;

  if (fetch && NAME_RE.test(st.remote)) {
    const f = await git(root, ['fetch', '--quiet', st.remote], { timeout: interactive ? 90000 : 25000, interactive });
    if (f.ok) st.fetched = true;
    else st.fetchError = describeError(f);
  }
  if (gitDir) {
    try {
      st.lastFetch = fs.statSync(path.join(gitDir, 'FETCH_HEAD')).mtime.toISOString();
    } catch {
      /* never checked on this computer */
    }
  }

  const counts = await git(root, ['rev-list', '--left-right', '--count', 'HEAD...@{u}']);
  if (counts.ok) [st.ahead, st.behind] = counts.stdout.split(/\s+/).map(Number);
  const fmt = '--format=%h%x09%an%x09%cI%x09%s';
  const [inc, out, files] = await Promise.all([
    st.behind ? git(root, ['log', fmt, '-n', '15', 'HEAD..@{u}']) : null,
    st.ahead ? git(root, ['log', fmt, '-n', '15', '@{u}..HEAD']) : null,
    st.behind ? git(root, ['diff', '--name-only', 'HEAD', '@{u}']) : null,
  ]);
  if (inc?.ok) st.incoming = parseLog(inc.stdout);
  if (out?.ok) st.outgoing = parseLog(out.stdout);
  if (files?.ok) {
    const names = files.stdout ? files.stdout.split('\n') : [];
    st.incomingFiles = names.slice(0, MAX_LISTED);
    st.needsSetup = names.some((n) => n === 'dependencies.json' || n === 'package.json');
    // running server and page stay on old version until restarted
    st.needsRestart = names.some((n) => /^(ui\/|scripts\/)/.test(n) || n === 'package.json');
  }
  st.state = st.ahead && st.behind ? 'diverged' : st.behind ? 'behind' : st.ahead ? 'ahead' : 'synced';
  return st;
}

export async function repoStatus(root, opts = {}) {
  const st = await computeStatus(root, opts);
  st.summary = describeStatus(st);
  return st;
}

/** Brief summary sentence of current state. Used by CLI and UI. */
export function describeStatus(st) {
  const fileStr = t.n('repo.status.file', st.changesTotal);
  const dirty = st.changesTotal ? t('repo.status.dirty', { count: st.changesTotal, files: fileStr }) : '';
  switch (st.state) {
    case 'no-git':
      return t('repo.status.noGit');
    case 'no-repo':
      return t('repo.status.noRepo');
    case 'detached':
      return t('repo.status.detached');
    case 'in-progress':
      return t('repo.status.inProgress');
    case 'no-remote':
      return t('repo.status.noRemote');
    case 'no-upstream':
      return t('repo.status.noUpstream', { branch: st.branch });
    case 'behind': {
      const updates = t.n('repo.status.updates', st.behind, { count: st.behind });
      return t('repo.status.behind', { updates, dirty });
    }
    case 'ahead': {
      const changes = t.n('repo.status.savedChanges', st.ahead, { count: st.ahead });
      return t('repo.status.ahead', { changes, dirty });
    }
    case 'diverged':
      return t('repo.status.diverged', { ahead: st.ahead, behind: st.behind, dirty });
    default:
      return st.changesTotal ? t('repo.status.syncedWithDirty', { count: st.changesTotal, files: fileStr }) : t('repo.status.synced');
  }
}

export const STASH_MESSAGE = 'ai-hub: changes set aside before pull';
const listOf = (files) => (files.length > 3 ? t('repo.moreItems', { list: files.slice(0, 3).join(', '), count: files.length - 3 }) : files.join(', '));

/**
 * Downloads updates only if they are a clean fast-forward.
 * If updates touch locally modified files, local changes are stashed, updates pulled, and changes reapplied.
 * Returns { ok, changed, message, from, to, files, needsSetup, reapplied, setAside, error?, status }.
 */
export async function pullUpdates(root, { interactive = true, setAside = false } = {}) {
  const st = await repoStatus(root, { fetch: true, interactive });
  const done = (extra) => ({ ok: false, changed: false, status: st, ...extra });
  if (st.fetchError) return done({ error: st.fetchError, message: st.fetchError.message });
  if (st.state === 'synced' || st.state === 'ahead') return done({ ok: true, message: st.state === 'ahead' ? t('repo.pull.noUpdates') : t('repo.pull.alreadyUpToDate') });
  if (st.state !== 'behind') return done({ message: describeStatus(st) });
  if (!UPSTREAM_RE.test(st.upstream ?? '') || !SHA_RE.test((st.head ?? '').slice(0, 40))) return done({ message: t('repo.pull.invalidState') });
  if (st.conflicts) return done({ message: t('repo.pull.conflicts') });

  // GENERATED files rewritten automatically by the hub (e.g. GUIDE.md after install): if changed on GitHub
  // they would block the pull. Reset them to HEAD; caller regenerates after pull.
  const [localMod, incoming] = await Promise.all([git(root, ['diff', '--name-only', 'HEAD']), git(root, ['diff', '--name-only', 'HEAD', st.upstream])]);
  const incomingSet = new Set(incoming.ok && incoming.stdout ? incoming.stdout.split('\n') : []);
  const regenerate = (localMod.ok && localMod.stdout ? localMod.stdout.split('\n') : []).filter((f) => GENERATED_FILES.includes(f) && incomingSet.has(f));
  if (regenerate.length) {
    const restore = await git(root, ['checkout', '--', ...regenerate]);
    if (!restore.ok) {
      const error = describeError(restore);
      return done({ error, message: error.message });
    }
  }

  // unpushed local changes on incoming files: stash them (tracked files only)
  const nowMod = await git(root, ['diff', '--name-only', 'HEAD']);
  const overlap = (nowMod.ok && nowMod.stdout ? nowMod.stdout.split('\n') : []).filter((f) => incomingSet.has(f));
  if (overlap.length) {
    const stash = await git(root, ['stash', 'push', '--quiet', '-m', STASH_MESSAGE]);
    if (!stash.ok) {
      const error = describeError(stash);
      return done({ error, message: error.message });
    }
  }

  // Without hooks: post-merge would trigger sync, which with many skills can take minutes.
  // After pull the interface or terminal prompts for sync.
  const noHooks = path.join(root, '.git', 'ai-hub-no-hooks');
  const merge = await git(root, ['-c', `core.hooksPath=${noHooks}`, 'merge', '--ff-only', '--quiet', st.upstream], { timeout: 120000 });
  if (!merge.ok) {
    if (overlap.length) await git(root, ['stash', 'pop', '--quiet']); // nothing downloaded: restore local changes
    const error = describeError(merge);
    return done({ error, message: error.message });
  }
  let reapplied = [];
  let setAsideFiles = [];
  if (overlap.length) {
    const apply = await git(root, ['stash', 'apply', '--quiet']);
    if (apply.ok) {
      await git(root, ['stash', 'drop', '--quiet']);
      reapplied = overlap;
    } else {
      // same lines: remove conflict markers (changes are safely preserved in stash)
      await git(root, ['reset', '--hard', '--quiet']);
      if (!setAside) {
        // revert to exact state prior to pull
        await git(root, ['reset', '--hard', '--quiet', st.head]);
        await git(root, ['stash', 'pop', '--quiet']);
        const message = t('repo.pull.sameLines', { files: listOf(overlap) });
        return done({ error: { kind: 'same-lines', message, detail: overlap.join('\n') }, message, overlap });
      }
      setAsideFiles = overlap;
    }
  }
  const after = await repoStatus(root);
  const got = t.n('repo.pull.downloaded', st.behind, { count: st.behind });
  const message = reapplied.length
    ? t('repo.pull.reapplied', { got, files: listOf(reapplied) })
    : setAsideFiles.length
      ? t('repo.pull.setAside', { got, files: listOf(setAsideFiles), stash: STASH_MESSAGE })
      : got;
  return { ok: true, changed: true, from: st.head, to: after.head, files: st.incomingFiles, count: st.behind, needsSetup: st.needsSetup, needsRestart: Boolean(st.needsRestart), regenerate, reapplied, setAside: setAsideFiles, message, status: after };
}

const cleanMessage = (m) => String(m ?? '').replace(/[\r\n\t]+/g, ' ').replace(/\0/g, '').trim().slice(0, 200);
export const defaultCommitMessage = (now = new Date()) => {
  const p = (x) => String(x).padStart(2, '0');
  const date = `${now.getFullYear()}-${p(now.getMonth() + 1)}-${p(now.getDate())} ${p(now.getHours())}:${p(now.getMinutes())}`;
  return t('repo.defaultCommitMessage', { platform: platformLabel(), date });
};

/**
 * Commits uncommitted changes (if any) and pushes to GitHub. Never force pushes.
 * Stops if pull is needed, if files look like secrets, or if git identity is unconfigured.
 */
export async function pushChanges(root, { message, interactive = true } = {}) {
  const st = await repoStatus(root, { fetch: true, interactive });
  const done = (extra) => ({ ok: false, committed: false, pushed: 0, status: st, ...extra });
  if (st.fetchError) return done({ error: st.fetchError, message: st.fetchError.message });
  if (st.state === 'behind' || st.state === 'diverged') return done({ message: st.state === 'behind' ? t('repo.push.pullFirst') : describeStatus(st) });
  if (!['synced', 'ahead'].includes(st.state)) return done({ message: describeStatus(st) });
  if (st.conflicts) return done({ message: t('repo.push.conflicts') });
  if (st.blocked.length) {
    const list = st.blocked.map((p) => `${p} (${st.blockedReasons?.[p] ?? t('repo.push.looksLikeSecret')})`).join('; ');
    const more = st.blockedTotal > st.blocked.length ? t('repo.push.moreSecrets', { count: st.blockedTotal - st.blocked.length }) : '';
    return done({ message: t('repo.push.blockedSecrets', { list, more }) });
  }
  if (!st.changesTotal && !st.ahead) return done({ ok: true, message: t('repo.push.nothingToSend') });
  if (!NAME_RE.test(st.remote) || !BRANCH_RE.test(st.upstream.slice(st.remote.length + 1)) || st.upstream.includes('..')) return done({ message: t('repo.push.invalidBranch') });

  let committed = false;
  if (st.changesTotal) {
    const [name, email] = await Promise.all([git(root, ['config', 'user.name']), git(root, ['config', 'user.email'])]);
    const errText = errorText().identity;
    if (!name.stdout || !email.stdout) return done({ error: { kind: 'identity', message: errText, detail: '' }, message: errText });
    const add = await git(root, ['add', '-A']);
    if (!add.ok) {
      const error = describeError(add);
      return done({ error, message: error.message });
    }
    const commit = await git(root, ['commit', '--quiet', '-m', cleanMessage(message) || defaultCommitMessage()], { timeout: 60000 });
    if (!commit.ok && !/nothing to commit/i.test(`${commit.stdout}${commit.stderr}`)) {
      const error = describeError(commit);
      return done({ error, message: error.message });
    }
    committed = commit.ok;
  }

  const branch = st.upstream.slice(st.remote.length + 1);
  const push = await git(root, ['push', '--quiet', st.remote, `HEAD:refs/heads/${branch}`], { timeout: 120000, interactive });
  const after = await repoStatus(root);
  if (!push.ok) {
    const error = describeError(push);
    return { ok: false, committed, pushed: 0, error, message: committed ? t('repo.push.savedLocallyFailed', { error: error.message }) : error.message, status: after };
  }
  const total = st.ahead + (committed ? 1 : 0);
  return { ok: true, committed, pushed: total, message: t.n('repo.push.pushed', total, { count: total }), status: after };
}
